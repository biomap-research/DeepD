    p.add_argument("--species", choices=["maize", "human", "custom"], required=True)
    p.add_argument("--annotation_csv", type=Path, required=True, help="Synced annotation CSV; row order must match all_probabilities.npy")
    p.add_argument("--results_root", type=Path, required=True, help="XGBoost output root containing xgboost_fixed/<model_tag>/...")
    p.add_argument("--model_tags", type=str, default="8kb_model,1m_model", help="Comma-separated model tags to plot separately")
    p.add_argument("--annotations", type=str, default=None, help="Comma-separated labels in top-to-bottom order")
    p.add_argument("--main_labels", type=str, default="", help="Labels used for exclusive/priority truth definitions; default by species")
    p.add_argument("--truth_mode", choices=["raw", "exclusive", "priority"], default="raw",
                   help="raw=biological label as-is; exclusive=only_LABEL; priority=CDS>UTR>intron style target")
    p.add_argument("--priority_labels", type=str, default="CDS,UTR,intron", help="Priority order for --truth_mode priority")
