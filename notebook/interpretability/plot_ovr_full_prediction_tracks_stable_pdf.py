def downsample_for_plot(pos: np.ndarray, score: np.ndarray, truth: np.ndarray, max_points: int, method: str) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Optional vector-size reduction. Truth is aggregated by max within bins."""
    n = len(pos)
    if max_points <= 0 or n <= max_points:
        return pos, score, truth
    method = str(method).lower()
    bins = np.linspace(0, n, max_points + 1, dtype=int)
    xs = []
    ys = []
    ts = []
    for a, b in zip(bins[:-1], bins[1:]):
        if b <= a:
            continue
        p = pos[a:b]
        s = score[a:b]
        t = truth[a:b]
        xs.append(float(np.mean(p)))
        if method == "max":
            ys.append(float(np.nanmax(s)))
        elif method == "median":
            ys.append(float(np.nanmedian(s)))
        else:
            ys.append(float(np.nanmean(s)))
        ts.append(bool(np.nanmax(t) > 0))
    return np.asarray(xs, dtype=float), np.asarray(ys, dtype=float), np.asarray(ts, dtype=bool)


def collapse_duplicates(
    pos: np.ndarray,
    score: np.ndarray,
    truth: np.ndarray,
    policy: str,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    policy = str(policy).lower()
    order = np.argsort(pos, kind="mergesort")
    pos = np.asarray(pos)[order]
    score = np.asarray(score)[order]
    truth = np.asarray(truth)[order].astype(bool)
    if policy == "none":
        return pos.astype(float), score.astype(float), truth

    tmp = pd.DataFrame({"pos": pos, "score": score, "truth": truth.astype(np.uint8)})
    if policy == "first":
        g = tmp.groupby("pos", sort=True, as_index=False).agg(score=("score", "first"), truth=("truth", "max"))
    elif policy == "mean":
        g = tmp.groupby("pos", sort=True, as_index=False).agg(score=("score", "mean"), truth=("truth", "max"))
    elif policy == "max":
        g = tmp.groupby("pos", sort=True, as_index=False).agg(score=("score", "max"), truth=("truth", "max"))
    else:
        raise ValueError("--duplicate_policy must be one of none, first, mean, or max")
    return g["pos"].to_numpy(dtype=float), g["score"].to_numpy(dtype=float), (g["truth"].to_numpy(dtype=np.uint8) > 0)


def draw_step_polygon_chunked(
    ax,
    x: np.ndarray,
    y: np.ndarray,
    color: str,
    alpha: float = 1.0,
    baseline: float = 0.0,
    chunk_size: int = 2500,
    rasterized: bool = False,
) -> int:
    """Draw filled step polygons as multiple vector chunks to keep SVG/PDF manageable."""
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    valid = np.isfinite(x) & np.isfinite(y)
    if not np.any(valid):
        return 0
    x, y = x[valid], np.clip(y[valid], 0, 1)
    n = len(x)
    if n < 2:
        return 0
    chunk_size = max(2, int(chunk_size))
    n_poly = 0
    for start in range(0, n, chunk_size):
        end = min(start + chunk_size + 1, n)
        xc = x[start:end]
        yc = y[start:end]
        if len(xc) < 2:
            continue
        verts = [(float(xc[0]), baseline)]
        for i in range(len(xc) - 1):
            mid = (float(xc[i]) + float(xc[i + 1])) / 2.0
            verts.append((float(xc[i]), float(yc[i])))
            verts.append((mid, float(yc[i])))
            verts.append((mid, float(yc[i + 1])))
        verts.append((float(xc[-1]), float(yc[-1])))
        verts.append((float(xc[-1]), baseline))
        patch = Polygon(
            verts,
            closed=True,
            facecolor=color,
            edgecolor="none",
            linewidth=0,
            alpha=alpha,
            zorder=2,
            rasterized=rasterized,
        )
        ax.add_patch(patch)
        n_poly += 1
    return n_poly


def estimate_step_width(pos: np.ndarray) -> float:
    pos = np.asarray(pos, dtype=float)
    if len(pos) < 2:
        return 1.0
    diffs = np.diff(np.sort(np.unique(pos)))
    diffs = diffs[diffs > 0]
    if len(diffs) == 0:
        return 1.0
    return float(np.median(diffs))


def mask_to_intervals(pos: np.ndarray, mask: np.ndarray, max_gap: Optional[float] = None) -> List[Tuple[float, float]]:
    pos = np.asarray(pos, dtype=float)
    mask = np.asarray(mask, dtype=bool)
    valid = np.isfinite(pos)
    pos = pos[valid]
    mask = mask[valid]
    if len(pos) == 0 or not np.any(mask):
        return []
    order = np.argsort(pos, kind="mergesort")
    pos = pos[order]
    mask = mask[order]
    step = estimate_step_width(pos)
    if max_gap is None or max_gap <= 0:
        max_gap = max(1.5 * step, step + 1e-9)

    intervals: List[Tuple[float, float]] = []
    active = False
    start = None
    last = None
    for p, m in zip(pos, mask):
        if bool(m):
            if not active:
                start = p
                active = True
            elif last is not None and (p - last) > max_gap:
                intervals.append((float(start), float(last + step)))
                start = p
            last = p
        else:
            if active:
                intervals.append((float(start), float(last + step)))
                active = False
                start = None
                last = None
    if active and start is not None and last is not None:
        intervals.append((float(start), float(last + step)))
    return intervals


def draw_truth_boxes(
    ax,
    pos: np.ndarray,
    truth: np.ndarray,
    color: str,
    height: float,
    alpha: float,
    ymin: float = -0.20,
    max_gap: Optional[float] = None,
) -> int:
    """Draw truth annotation blocks below the prediction baseline.

    The browser-style figure is easier to read when the blue truth blocks sit below
    y=0 instead of covering the 0 tick/grid line.  The axis y-limit includes this
    negative range, so the rectangles remain fully vector-editable and are not
    clipped.
    """
    intervals = mask_to_intervals(pos, truth, max_gap=max_gap)
    for s, e in intervals:
        ax.add_patch(
            Rectangle(
                (s, ymin),
                e - s,
                height,
                facecolor=color,
                edgecolor="none",
                linewidth=0,
                alpha=alpha,
                zorder=4,
            )
        )
    return len(intervals)


def style_track_axis(
    ax,
    label: str,
    x_start: float,
    x_end: float,
    label_pad: float,
    font_size: float,
    show_y_axis: bool = True,
    y_min: float = -0.26,
    y_max: float = 1.05,
) -> None:
    ax.set_xlim(x_start, x_end)
    ax.set_ylim(y_min, y_max)
    ax.set_yticks([0, 1])
    ax.set_yticklabels(["0", "1"], fontsize=max(7, font_size - 2))
    ax.set_ylabel(label, fontsize=font_size, rotation=0, labelpad=label_pad, va="center", ha="right")
    ax.grid(axis="y", linestyle="--", linewidth=0.7, color="#e9e9e9", alpha=1.0, zorder=0)
    ax.tick_params(axis="x", bottom=False, labelbottom=False, length=0)
    ax.tick_params(axis="y", length=2, width=0.8, pad=2)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["bottom"].set_visible(False)
    ax.spines["left"].set_visible(bool(show_y_axis))
    if show_y_axis:
        ax.spines["left"].set_linewidth(0.8)


def save_figure(fig, out_stem: Path, formats: Sequence[str], dpi: int) -> List[Path]:
    paths = []
    for fmt in formats:
        out = out_stem.with_suffix(f".{fmt}")
        fig.savefig(out, dpi=dpi, bbox_inches="tight", facecolor="white", edgecolor="none", transparent=False)
        paths.append(out)
        mprint(f"[SAVE] {out}")
    plt.close(fig)
    return paths


