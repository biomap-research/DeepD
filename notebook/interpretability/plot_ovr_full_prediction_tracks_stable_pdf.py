def numeric_bool_col(df: pd.DataFrame, col: str) -> np.ndarray:
    if col not in df.columns:
        return np.zeros(len(df), dtype=bool)
    return pd.to_numeric(df[col], errors="coerce").fillna(0).to_numpy() > 0


def add_derived_labels(df: pd.DataFrame, species: str, force: bool = False) -> pd.DataFrame:
    """Create UTR / TE_DNA aliases when they are absent or explicitly requested."""
    out = df.copy()
    species_l = str(species).lower()

    if species_l == "maize":
        # UTR = five_prime_UTR OR three_prime_UTR.
        utr_sources = [c for c in ["five_prime_UTR", "three_prime_UTR", "is_five_prime_UTR", "is_three_prime_UTR"] if c in out.columns]
        if utr_sources and (force or "UTR" not in out.columns):
            vals = np.zeros(len(out), dtype=bool)
            for c in utr_sources:
                vals |= numeric_bool_col(out, c)
            out["UTR"] = vals.astype(np.uint8)

        # TE_DNA = user-specified DNA/MITE subclasses. Also accept any TE_DNA_* or TE_MITE_* column.
        te_sources = [c for c in MAIZE_TE_DNA_SOURCE_COLS if c in out.columns]
        te_sources += [c for c in out.columns if (c.startswith("TE_DNA_") or c.startswith("TE_MITE_")) and c not in te_sources]
        if te_sources and (force or "TE_DNA" not in out.columns):
            vals = np.zeros(len(out), dtype=bool)
            for c in te_sources:
                vals |= numeric_bool_col(out, c)
            out["TE_DNA"] = vals.astype(np.uint8)

    # Common aliases.
    if "CRE" not in out.columns and "cCRE" in out.columns and species_l == "maize":
        out["CRE"] = numeric_bool_col(out, "cCRE").astype(np.uint8)
    if "cCRE" not in out.columns and "CRE" in out.columns and species_l == "human":
        # Only an alias fallback; normally human annotations already use cCRE.
        out["cCRE"] = numeric_bool_col(out, "CRE").astype(np.uint8)

    return out


def compute_truth_masks(
    df: pd.DataFrame,
    labels: Sequence[str],
    main_labels: Sequence[str],
    truth_mode: str,
    priority_labels: Sequence[str],
) -> Dict[str, np.ndarray]:
    """Return boolean truth masks for plotting.

    truth_mode:
      raw       : each label uses its biological annotation column directly.
      exclusive : label is true only if exactly one of main_labels is positive and it is this label.
      priority  : priority_labels are assigned in order; remaining labels use exclusive one-label definition.
                  This matches the maize priority sampling design: CDS > UTR > intron.
    """
    raw: Dict[str, np.ndarray] = {lab: numeric_bool_col(df, lab) for lab in main_labels}
    for lab in labels:
        if lab not in raw:
            raw[lab] = numeric_bool_col(df, lab)

    truth_mode = str(truth_mode).lower()
    if truth_mode == "raw":
        return {lab: raw.get(lab, numeric_bool_col(df, lab)) for lab in labels}

    raw_matrix = np.vstack([raw.get(lab, np.zeros(len(df), dtype=bool)) for lab in main_labels]).T
    n_positive = raw_matrix.sum(axis=1)

    if truth_mode == "exclusive":
        return {lab: (raw.get(lab, np.zeros(len(df), dtype=bool)) & (n_positive == 1)) for lab in labels}

    if truth_mode == "priority":
        out: Dict[str, np.ndarray] = {}
        already_assigned = np.zeros(len(df), dtype=bool)
        priority_set = set(priority_labels)
        for lab in priority_labels:
            lab_mask = raw.get(lab, np.zeros(len(df), dtype=bool)) & (~already_assigned)
            if lab in labels:
                out[lab] = lab_mask
            already_assigned |= lab_mask
        # Non-priority labels match the original fixed-token design: only_LABEL.
        for lab in labels:
            if lab in out:
                continue
            out[lab] = raw.get(lab, np.zeros(len(df), dtype=bool)) & (n_positive == 1)
        return out

    raise ValueError(f"Unknown --truth_mode={truth_mode}; choose raw, exclusive, or priority")


