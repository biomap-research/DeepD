    p.add_argument("--bottom_margin", type=float, default=0.60)
    p.add_argument("--hspace", type=float, default=0.32, help="Vertical spacing between tracks. Larger values prevent 0/1 y-tick label overlap.")
    p.add_argument("--label_pad", type=float, default=34.0)
