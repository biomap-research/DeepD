def prepare_region_indices(df: pd.DataFrame, chrom_col: str, pos_col: str, chrom: str, start: int, end: int) -> np.ndarray:
    pos_values = pd.to_numeric(df[pos_col], errors="coerce").to_numpy()
    chrom_values = df[chrom_col].astype(str).to_numpy()
    mask = (chrom_values == str(chrom)) & np.isfinite(pos_values) & (pos_values >= start) & (pos_values < end)
    return np.flatnonzero(mask)


def make_track_label(run: BestRun, show_best_info: bool) -> str:
    base = display_label(run.label)
    if not show_best_info:
        return base
    return f"{base}\nL{run.layer_num:03d}, AP={run.score:.3f}"


