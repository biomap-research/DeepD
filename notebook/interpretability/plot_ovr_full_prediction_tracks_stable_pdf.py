def candidate_summary_files(model_root: Path, label: str) -> List[Path]:
    patterns = [
        f"layer_*/one_vs_rest/{label}/result_summary.json",
        f"layer_*/one_vs_rest/{label}/*/result_summary.json",
        f"layer_*/{label}/result_summary.json",
        f"layer_*/{label}/*/result_summary.json",
    ]
    out: List[Path] = []
    for pat in patterns:
        out.extend(model_root.glob(pat))
    return sorted(dict.fromkeys(out))


def load_json(path: Path) -> Mapping[str, object]:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def find_best_run_for_label(
    model_root: Path,
    model_tag: str,
    label: str,
    metric: str,
    prefer_metric_fallbacks: Sequence[str],
) -> Optional[BestRun]:
    files = candidate_summary_files(model_root, label)
    if not files:
        return None

    best: Optional[BestRun] = None
    metric_candidates = [metric] + [m for m in prefer_metric_fallbacks if m != metric]

    for summary_path in files:
        try:
            data = load_json(summary_path)
        except Exception as exc:
            mprint(f"[WARN] Cannot read {summary_path}: {exc}")
            continue

        value = float("nan")
        metric_used = metric
        for m in metric_candidates:
            value = safe_float(data.get(m), default=float("nan"))
            if math.isfinite(value):
                metric_used = m
                break
        if not math.isfinite(value):
            continue

        # Locate probability file in the same task directory.
        prob_path = summary_path.parent / "all_probabilities.npy"
        if not prob_path.exists():
            # Older or non-full-prediction runs might not have this file. Do not silently use selected rows.
            continue

        layer = normalize_layer_name(data.get("layer", summary_path.parts[-4] if len(summary_path.parts) >= 4 else ""))
        layer_num = layer_num_from_name(layer)
        best_iteration = data.get("best_iteration", None)
        if isinstance(best_iteration, str):
            try:
                best_iteration = int(best_iteration)
            except Exception:
                best_iteration = None
        elif best_iteration is not None:
            try:
                best_iteration = int(best_iteration)
            except Exception:
                best_iteration = None

        current = BestRun(
            label=label,
            model_tag=model_tag,
            layer=layer,
            layer_num=layer_num,
            score=value,
            summary_path=summary_path,
            prob_path=prob_path,
            best_iteration=best_iteration,
            metric_name=metric_used,
            raw_summary=data,
        )
        if best is None:
            best = current
        else:
            # Tie-breaker: higher metric, then lower test_logloss, then lower layer number.
            best_loss = safe_float(best.raw_summary.get("test_logloss"), default=float("inf"))
            cur_loss = safe_float(current.raw_summary.get("test_logloss"), default=float("inf"))
            if (current.score > best.score) or (
                math.isclose(current.score, best.score) and (cur_loss < best_loss or (math.isclose(cur_loss, best_loss) and current.layer_num < best.layer_num))
            ):
                best = current
    return best


def load_probability_vector(path: Path) -> np.ndarray:
    arr = np.load(path, mmap_mode="r")
    if arr.ndim == 1:
        return np.asarray(arr, dtype=np.float32)
    if arr.ndim == 2:
        if arr.shape[1] == 1:
            return np.asarray(arr[:, 0], dtype=np.float32)
        # Common binary predict_proba format: column 1 is positive probability.
        return np.asarray(arr[:, 1], dtype=np.float32)
    raise ValueError(f"Unsupported probability array shape: {path} shape={arr.shape}")


