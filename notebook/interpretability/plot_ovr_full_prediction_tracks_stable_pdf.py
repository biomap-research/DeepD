def main() -> None:
    args = build_arg_parser().parse_args()
    if args.end <= args.start:
        raise ValueError("--end must be greater than --start")

    annotations = choose_annotation_order(args.species, args.annotations)
    main_labels = choose_main_labels(args.species, annotations, args.main_labels)
    priority_labels = parse_csv_list(args.priority_labels)
    model_tags = parse_csv_list(args.model_tags)
    metric_fallbacks = parse_csv_list(args.metric_fallbacks)
    if not model_tags:
        raise ValueError("--model_tags must not be empty")

    args.output_dir.mkdir(parents=True, exist_ok=True)

    mprint(f"[LOAD] annotations: {args.annotation_csv}")
    df = pd.read_csv(args.annotation_csv)
    df = add_derived_labels(df, args.species, force=args.force_recompute_derived)
    chrom_col = infer_chrom_col(df, args.chrom_col)
    pos_col = infer_pos_col(df, args.pos_col)
    mprint(f"[INFO] rows={len(df):,}; chrom_col={chrom_col}; pos_col={pos_col}")
    mprint(f"[INFO] annotations={annotations}")
    mprint(f"[INFO] truth_mode={args.truth_mode}; main_labels={main_labels}; priority_labels={priority_labels}")

    missing_annotation_cols = [lab for lab in set(annotations + main_labels) if lab not in df.columns]
    if missing_annotation_cols:
        mprint(f"[WARN] These annotation columns are absent and will be treated as all-zero: {missing_annotation_cols}")

    truth_masks = compute_truth_masks(
        df=df,
        labels=annotations,
        main_labels=main_labels,
        truth_mode=args.truth_mode,
        priority_labels=priority_labels,
    )

    region_idx = prepare_region_indices(df, chrom_col, pos_col, args.region, args.start, args.end)
    if len(region_idx) == 0:
        raise ValueError(f"No data found in region {args.region}:{args.start}-{args.end} using {chrom_col}/{pos_col}")
    n_unique_pos = pd.Series(pd.to_numeric(df.iloc[region_idx][pos_col], errors="coerce")).nunique()
    mprint(f"[INFO] region rows={len(region_idx):,}; unique positions={n_unique_pos:,}")

    all_summary_rows: List[Dict[str, object]] = []
    for model_tag in model_tags:
        model_root = find_model_root(args.results_root, model_tag)
        mprint(f"\n[MODEL] {model_tag} -> {model_root}")
        best_runs: List[BestRun] = []
        for lab in annotations:
            run = find_best_run_for_label(model_root, model_tag, lab, args.metric, metric_fallbacks)
            if run is None:
                msg = f"{model_tag}: no one_vs_rest result with all_probabilities.npy found for label={lab}"
                if args.allow_missing_labels:
                    mprint(f"[SKIP] {msg}")
                    continue
                raise FileNotFoundError(msg)
            best_runs.append(run)
            mprint(f"  {lab:<24} best={run.layer:<10} {run.metric_name}={run.score:.5f} prob={run.prob_path.name}")

        if not best_runs:
            mprint(f"[WARN] model={model_tag} has no plottable labels; skipping")
            continue
        out_stem = args.output_dir / f"{args.prefix}_{model_tag}_{args.region}_{args.start}_{args.end}"
        ret = plot_tracks_for_model(df, truth_masks, region_idx, pos_col, best_runs, args, model_tag, out_stem)
        all_summary_rows.extend(ret["summary_rows"])

    if all_summary_rows:
        summary_df = pd.DataFrame(all_summary_rows)
        summary_path = args.output_dir / f"{args.prefix}_{args.region}_{args.start}_{args.end}_plotted_tracks_summary.csv"
        summary_df.to_csv(summary_path, index=False)
        mprint(f"[SAVE] {summary_path}")

    mprint("\nDone.")


if __name__ == "__main__":
    main()
